/* Build the SEO and link-preview parts of the site from assets/js/data.js.

   Usage (from the site folder):  node tools/build-pages.cjs

   - Rewrites the block between <!-- SEO:START --> and <!-- SEO:END --> in
     index.html (title, description, Open Graph / WhatsApp preview, schema.org)
   - Writes stays/<id>/index.html for every property: the same page, but with
     that property's own title, description and preview image, opening on it
   - Writes sitemap.xml and robots.txt

   Re-run after editing listings in data.js or changing SITE.url (new domain).
   Preview images come from tools/make_og_images.py. */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, text) => {
  fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, f), text);
};

// data.js declares its content with const, so return it from the script
const { SITE, STAYS } = vm.runInNewContext(read('assets/js/data.js') + '\n;({ SITE, STAYS })');
const URL_BASE = SITE.url.endsWith('/') ? SITE.url : SITE.url + '/';
const TODAY = new Date().toISOString().slice(0, 10);
const PHONE_INTL = '+' + SITE.whatsapp;

const attr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const text = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const jsonLd = obj => JSON.stringify(obj, null, 1).replace(/</g, '\\u003c');
const clip = (s, n = 158) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(' ', n - 1)).replace(/[,.;:\s]+$/, '') + '…');

const ADDRESS = { '@type': 'PostalAddress', addressLocality: 'Marloth Park', addressRegion: 'Mpumalanga', postalCode: '1321', addressCountry: 'ZA' };

function headBlock({ base, title, description, url, image, imageAlt, schema }) {
  return `<!-- SEO:START (generated by tools/build-pages.cjs — edit data.js and re-run, not this block) -->
<base href="${base}" />
<title>${text(title)}</title>
<meta name="description" content="${attr(description)}" />
<link rel="canonical" href="${url}" />
<meta name="robots" content="index, follow, max-image-preview:large" />
<meta property="og:type" content="website" />
<meta property="og:site_name" content="${attr(SITE.name)}" />
<meta property="og:locale" content="en_ZA" />
<meta property="og:title" content="${attr(title)}" />
<meta property="og:description" content="${attr(description)}" />
<meta property="og:url" content="${url}" />
<meta property="og:image" content="${image}" />
<meta property="og:image:secure_url" content="${image}" />
<meta property="og:image:type" content="image/jpeg" />
<meta property="og:image:width" content="1200" />
<meta property="og:image:height" content="630" />
<meta property="og:image:alt" content="${attr(imageAlt)}" />
<meta name="twitter:card" content="summary_large_image" />
<meta name="twitter:title" content="${attr(title)}" />
<meta name="twitter:description" content="${attr(description)}" />
<meta name="twitter:image" content="${image}" />
<script type="application/ld+json">${jsonLd(schema)}</script>
<!-- SEO:END -->`;
}

const template = read('index.html');
const blockRe = /<!-- SEO:START[\s\S]*?<!-- SEO:END -->/;
if (!blockRe.test(template)) throw new Error('index.html has no <!-- SEO:START --> … <!-- SEO:END --> block');

/* ---------- Home page ---------- */
const homeDescription = `Book ${STAYS.length} handpicked self-catering bush homes in Marloth Park, next to the Kruger National Park — pools, bomas and wildlife at your door — plus trusted local services.`;
const home = headBlock({
  base: './',
  title: 'Kruger Marloth Services & Bookings — Self-catering stays in Marloth Park',
  description: homeDescription,
  url: URL_BASE,
  image: URL_BASE + 'images/og/home.jpg',
  imageAlt: 'Holiday homes in Marloth Park next to the Kruger National Park',
  schema: {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'TravelAgency', '@id': URL_BASE + '#business', name: SITE.name, url: URL_BASE,
        description: homeDescription, logo: URL_BASE + 'logo.jpg', image: URL_BASE + 'images/og/home.jpg',
        telephone: PHONE_INTL, ...(SITE.email ? { email: SITE.email } : {}),
        address: ADDRESS, areaServed: ['Marloth Park', 'Kruger National Park', 'Komatipoort'],
      },
      { '@type': 'WebSite', '@id': URL_BASE + '#website', name: SITE.name, url: URL_BASE, inLanguage: 'en-ZA' },
    ],
  },
});
write('index.html', template.replace(blockRe, home));

/* ---------- One page per property ---------- */
for (const s of STAYS) {
  const url = `${URL_BASE}stays/${s.id}/`;
  const description = clip(`${s.tagline}. Self-catering for ${s.sleeps} guests — ${s.bedrooms} bedroom${s.bedrooms > 1 ? 's' : ''}, ${s.bathrooms} bathroom${s.bathrooms > 1 ? 's' : ''} — in Marloth Park next to the Kruger. ${s.description}`);
  const photos = Array.from({ length: Math.min(s.photos, 6) }, (_, i) => `${URL_BASE}images/stays/${s.id}/${String(i + 1).padStart(2, '0')}.jpg`);
  const block = headBlock({
    base: '../../',
    title: `${s.name} | Self-catering in Marloth Park`,
    description,
    url,
    image: `${URL_BASE}images/og/${s.id}.jpg`,
    imageAlt: `${s.name}, Marloth Park`,
    schema: {
      '@context': 'https://schema.org',
      '@graph': [
        {
          '@type': 'LodgingBusiness', '@id': url + '#stay', name: s.name, url, description: s.description, image: photos,
          telephone: PHONE_INTL, address: ADDRESS, numberOfRooms: s.bedrooms,
          amenityFeature: s.amenities.map(([, label]) => ({ '@type': 'LocationFeatureSpecification', name: label, value: true })),
          containedInPlace: { '@type': 'Place', name: 'Marloth Park' },
          provider: { '@id': URL_BASE + '#business' },
        },
        {
          '@type': 'BreadcrumbList', itemListElement: [
            { '@type': 'ListItem', position: 1, name: 'Home', item: URL_BASE },
            { '@type': 'ListItem', position: 2, name: 'Stays', item: URL_BASE + '#stays' },
            { '@type': 'ListItem', position: 3, name: s.name, item: url },
          ],
        },
      ],
    },
  });
  // Crawlers and link previews don't run JavaScript, so include a plain summary too
  const fallback = `<noscript><main class="container" style="padding:40px 16px">
  <h1>${text(s.name)}</h1><p>${text(s.description)}</p>
  <ul>${s.amenities.map(([, label]) => `<li>${text(label)}</li>`).join('')}</ul>
  <p>Book with ${text(SITE.contactName)}: WhatsApp ${text(SITE.phone)}${SITE.email ? ' · ' + text(SITE.email) : ''}</p>
  <p><a href="./#stays">See all stays in Marloth Park</a></p></main></noscript>`;
  const page = template
    .replace(blockRe, block)
    .replace(/<body[^>]*>/, `<body data-stay="${s.id}">\n${fallback}`);
  write(`stays/${s.id}/index.html`, page);
}

/* ---------- Sitemap & robots ---------- */
const urlEntry = (loc, images = [], priority = '0.8') => `  <url>
    <loc>${loc}</loc>
    <lastmod>${TODAY}</lastmod>
    <priority>${priority}</priority>${images.map(i => `
    <image:image><image:loc>${i}</image:loc></image:image>`).join('')}
  </url>`;
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urlEntry(URL_BASE, [URL_BASE + 'images/og/home.jpg'], '1.0')}
${STAYS.map(s => urlEntry(`${URL_BASE}stays/${s.id}/`,
  Array.from({ length: Math.min(s.photos, 5) }, (_, i) => `${URL_BASE}images/stays/${s.id}/${String(i + 1).padStart(2, '0')}.jpg`))).join('\n')}
${urlEntry(URL_BASE + 'privacy.html', [], '0.3')}
</urlset>
`);

const basePath = new URL(URL_BASE).pathname;
write('robots.txt', `User-agent: *
Allow: /
Disallow: ${basePath}admin.html

Sitemap: ${URL_BASE}sitemap.xml
`);

console.log(`Built index.html, ${STAYS.length} property pages, sitemap.xml and robots.txt for ${URL_BASE}`);
